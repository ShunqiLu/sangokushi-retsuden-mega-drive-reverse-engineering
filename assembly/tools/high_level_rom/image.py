"""Pure, single-authority assembly of a one-MiB linear cartridge image.

Confidence: confirmed by the focused synthetic tests in ``test_image.py``.
Addresses are half-open linear BIN offsets, not SMD file offsets or bus aliases.
The core neither discovers sources nor loads files. Code and resource owners
supply their own immutable blocks; even byte-identical overlaps are rejected.
No missing bytes, copier-header bytes or cartridge checksums are invented.
"""
from __future__ import annotations

from dataclasses import dataclass
from typing import Iterable


IMAGE_SIZE = 0x100000
SMD_HEADER_SIZE = 0x200
SMD_BLOCK_SIZE = 0x4000
SMD_HALF_BLOCK_SIZE = 0x2000


class ImageError(ValueError):
    """Invalid image ownership, coverage or container input."""


def _integer(value: object, label: str) -> int:
    if type(value) is not int:
        raise ImageError(f"{label} must be an exact int, not bool or a subclass")
    return value


def _bytes(value: object, label: str) -> bytes:
    if type(value) is not bytes:
        raise ImageError(f"{label} must be immutable, exact bytes")
    return value


def _name(value: object, label: str) -> str:
    if type(value) is not str or not value.strip():
        raise ImageError(f"{label} must be a nonempty, non-whitespace string")
    return value


@dataclass(frozen=True)
class ImageInterval:
    """An explicit nonempty interval in the one-MiB physical authority."""

    start: int
    end: int

    def __post_init__(self) -> None:
        _integer(self.start, "interval start")
        _integer(self.end, "interval end")
        if not 0 <= self.start < self.end <= IMAGE_SIZE:
            raise ImageError("interval must satisfy 0 <= start < end <= 0x100000")

    @property
    def size(self) -> int:
        return self.end - self.start

    def __str__(self) -> str:
        return f"[0x{self.start:06X},0x{self.end:06X})"


@dataclass(frozen=True)
class ImageBlock:
    """Bytes generated by exactly one named code or resource source owner."""

    start: int
    data: bytes
    owner: str
    role: str

    def __post_init__(self) -> None:
        _integer(self.start, "block start")
        _bytes(self.data, "block data")
        _name(self.owner, "block owner")
        _name(self.role, "block role")
        if not self.data:
            raise ImageError("empty blocks do not establish byte ownership")
        if not 0 <= self.start < IMAGE_SIZE or self.end > IMAGE_SIZE:
            raise ImageError("block range must lie wholly within [0,0x100000)")

    @property
    def end(self) -> int:
        return self.start + len(self.data)

    @property
    def interval(self) -> ImageInterval:
        return ImageInterval(self.start, self.end)


@dataclass(frozen=True)
class ImageOverlap:
    """Two conflicting authorities and their precise shared interval."""

    left: ImageBlock
    right: ImageBlock
    shared: ImageInterval


class ImageOverlapError(ImageError):
    def __init__(self, conflicts: tuple[ImageOverlap, ...]):
        self.conflicts = conflicts
        descriptions = (
            f"owner={conflict.left.owner!r} role={conflict.left.role!r} "
            f"range={conflict.left.interval} conflicts with "
            f"owner={conflict.right.owner!r} role={conflict.right.role!r} "
            f"range={conflict.right.interval}; shared={conflict.shared}"
            for conflict in conflicts
        )
        super().__init__("image block ownership overlaps:\n" + "\n".join(descriptions))


class IncompleteImageError(ImageError):
    def __init__(self, gaps: tuple[ImageInterval, ...]):
        self.gaps = gaps
        super().__init__("image has unresolved intervals: " + ", ".join(map(str, gaps)))


def validate_blocks(blocks: Iterable[ImageBlock]) -> tuple[ImageBlock, ...]:
    """Sort and validate all blocks; report every intersection, not just neighbors.

    An alias is not an additional physical owner. This API deliberately has no
    'same bytes' exception; a future explicit alias validator must be separate.
    """
    materialized = tuple(blocks)
    for block in materialized:
        if type(block) is not ImageBlock:
            raise ImageError("each source must supply an exact ImageBlock")
        # Validate defensively even when a caller bypassed frozen construction.
        block.__post_init__()
    ordered = tuple(sorted(materialized, key=lambda block: (block.start, block.end, block.owner, block.role)))
    active: list[ImageBlock] = []
    conflicts: list[ImageOverlap] = []
    for block in ordered:
        active = [prior for prior in active if prior.end > block.start]
        for prior in active:
            conflicts.append(ImageOverlap(prior, block, ImageInterval(block.start, min(prior.end, block.end))))
        active.append(block)
    if conflicts:
        raise ImageOverlapError(tuple(conflicts))
    return ordered


def _gaps_in_ordered(blocks: tuple[ImageBlock, ...]) -> tuple[ImageInterval, ...]:
    gaps = []
    covered_until = 0
    for block in blocks:
        if covered_until < block.start:
            gaps.append(ImageInterval(covered_until, block.start))
        covered_until = block.end
    if covered_until < IMAGE_SIZE:
        gaps.append(ImageInterval(covered_until, IMAGE_SIZE))
    return tuple(gaps)


def find_gaps(blocks: Iterable[ImageBlock]) -> tuple[ImageInterval, ...]:
    """Return every uncovered physical interval; reject overlaps first."""
    return _gaps_in_ordered(validate_blocks(blocks))


def assemble_complete(blocks: Iterable[ImageBlock]) -> bytes:
    """Concatenate an exactly complete ownership partition, without padding.

    Owner and role are provenance rather than a parser or codec selector.
    Source generation and logical alias checks belong outside this pure core.
    """
    ordered = validate_blocks(blocks)
    gaps = _gaps_in_ordered(ordered)
    if gaps:
        raise IncompleteImageError(gaps)
    return b"".join(block.data for block in ordered)


def interleave_smd(linear: bytes, copier_header: bytes) -> bytes:
    """Pack one complete image with the caller's exact 512-byte copier header.

    Every 16-KiB block stores odd-address bytes first, then even-address bytes.
    The separate header is not detected, rewritten, trimmed or padded.
    """
    _bytes(linear, "linear image")
    _bytes(copier_header, "copier header")
    if len(linear) != IMAGE_SIZE:
        raise ImageError("SMD packing requires exactly 0x100000 linear bytes")
    if len(copier_header) != SMD_HEADER_SIZE:
        raise ImageError("SMD copier header must contain exactly 512 bytes")
    blocks = (
        linear[base + 1:base + SMD_BLOCK_SIZE:2] + linear[base:base + SMD_BLOCK_SIZE:2]
        for base in range(0, IMAGE_SIZE, SMD_BLOCK_SIZE)
    )
    return copier_header + b"".join(blocks)


def deinterleave_smd(smd: bytes) -> tuple[bytes, bytes]:
    """Return (linear image, exact caller-supplied copier header) losslessly."""
    _bytes(smd, "SMD image")
    if len(smd) != IMAGE_SIZE + SMD_HEADER_SIZE:
        raise ImageError("SMD input must contain 512 header bytes and 0x100000 payload bytes")
    payload = memoryview(smd)[SMD_HEADER_SIZE:]
    blocks = []
    for base in range(0, IMAGE_SIZE, SMD_BLOCK_SIZE):
        odd = payload[base:base + SMD_HALF_BLOCK_SIZE]
        even = payload[base + SMD_HALF_BLOCK_SIZE:base + SMD_BLOCK_SIZE]
        # Every output byte comes from an input pair; this is not gap filling.
        blocks.append(bytes(value for pair in zip(even, odd) for value in pair))
    return b"".join(blocks), smd[:SMD_HEADER_SIZE]
